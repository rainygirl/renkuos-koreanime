#!/usr/bin/env python3
"""Writes src/Icons.h: the 16x16 B_CMAP8 icons input_server shows in Deskbar
for the method -- "가" in Korean mode, "A" in English mode.

Run from the repository root: python3 tools/make_icons.py
"""
import os

BLACK = 0x00      # B_CMAP8 index of black
WHITE = 0x3F      # and of white
CLEAR = 0xFF      # B_TRANSPARENT_MAGIC_CMAP8

# '#' black, '.' white (the key cap), ' ' transparent
HAN = [
    " .............. ",
    "................",
    "................",
    "...######...##..",
    "........#...##..",
    "........#...##..",
    ".......##...####",
    ".......#....##..",
    "......##....##..",
    ".....##.....##..",
    "....##......##..",
    "...##.......##..",
    "................",
    "................",
    "................",
    " .............. ",
]

ROMAN = [
    " .............. ",
    "................",
    "................",
    "......####......",
    ".....##..##.....",
    ".....##..##.....",
    "....##....##....",
    "....##....##....",
    "....########....",
    "...##......##...",
    "...##......##...",
    "...##......##...",
    "................",
    "................",
    "................",
    " .............. ",
]


def emit(name, rows):
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), name
    values = []
    for row in rows:
        for c in row:
            values.append({"#": BLACK, ".": WHITE, " ": CLEAR}[c])
    lines = ["static const uchar %s[16 * 16] = {" % name]
    for i in range(0, 256, 16):
        lines.append("\t" + ", ".join("0x%02x" % v for v in values[i:i + 16])
                     + ",")
    lines.append("};")
    return "\n".join(lines)


if __name__ == "__main__":
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    body = "\n\n".join([emit("kHangulIcon", HAN), emit("kRomanIcon", ROMAN)])
    header = (
        "/*\n * Generated by tools/make_icons.py -- edit that, not this.\n */\n"
        "#ifndef KOREANIME_ICONS_H\n#define KOREANIME_ICONS_H\n\n"
        "#include <SupportDefs.h>\n\n\n" + body
        + "\n\n\n#endif\t// KOREANIME_ICONS_H\n")
    with open(os.path.join(root, "src", "Icons.h"), "w") as f:
        f.write(header)
    print("src/Icons.h written")
